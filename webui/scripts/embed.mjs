import { copyFile, mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { resolve } from 'node:path'
import { gzipSync } from 'node:zlib'
import { execFileSync } from 'node:child_process'

const root = fileURLToPath(new URL('../../', import.meta.url))
const output = resolve(root, 'uboot-mtk-20250711/failsafe/embedded/fsdata-bootstrap/vue')
await mkdir(output, { recursive: true })
execFileSync(process.execPath, [resolve(root, 'webui/node_modules/vite/bin/vite.js'), 'build', '--outDir', 'dist-no-i18n'], { cwd: resolve(root, 'webui'), env: { ...process.env, WEBUI_I18N: '0' }, stdio: 'inherit' })
await copyFile(resolve(root, 'webui/dist-no-i18n/app.js'), resolve(output, 'app-no-i18n.js'))
for (const file of ['index.html', 'app.js', 'app.css']) {
  await copyFile(resolve(root, 'webui/dist', file), resolve(output, file))
  const data = await readFile(resolve(output, file))
  console.log(`${file}: ${data.length} bytes / ${gzipSync(data, { level: 9 }).length} bytes gzip`)
}
// Only generated lazy assets are replaced. Keep both entry variants, with shared
// hashed chunks deduplicated and only the selected variant linked by Kbuild.
await rm(resolve(output, 'assets'), { recursive: true, force: true })
await mkdir(resolve(output, 'assets'), { recursive: true })
const variants = {}
for (const variant of ['dist', 'dist-no-i18n']) {
  const files = (await readdir(resolve(root, 'webui', variant, 'assets'))).filter(name => name.endsWith('.js')).sort()
  variants[variant] = files
  for (const name of files) await copyFile(resolve(root, 'webui', variant, 'assets', name), resolve(output, 'assets', name))
}
const make = ['# Generated by webui/scripts/embed.mjs. Do not edit.', 'ifeq ($(CONFIG_WEBUI_FAILSAFE_I18N),y)']
const header = ['/* Generated lazy asset allowlist. */', 'static const char *const vue_lazy_assets[] = {', '#ifdef CONFIG_WEBUI_FAILSAFE_I18N']
for (const [index, variant] of ['dist', 'dist-no-i18n'].entries()) {
  if (index) { make.push('else'); header.push('#else') }
  for (const name of variants[variant]) {
    if (!/^[a-zA-Z0-9_][a-zA-Z0-9_.-]*\.js$/.test(name)) throw new Error(`Unsafe asset name: ${name}`)
    const object = `vue_${name.replace(/[^a-zA-Z0-9_]/g, '_')}.o`
    make.push(`obj-y += ${object}`, `FILE_${object} := .min/vue/assets/${name}.gz`, `FSPATH_${object} := assets/${name}`, `$(obj)/${object}: $(obj)/.min/vue/assets/${name}.gz FORCE`, '\t$(call if_changed_dep,as_o_html)', '')
    header.push(`\t"/assets/${name}",`)
  }
}
make.push('endif', '')
header.push('#endif', '\tNULL', '};', '')
await writeFile(resolve(output, 'assets.mk'), make.join('\n'))
await writeFile(resolve(output, 'assets.h'), header.join('\n'))
