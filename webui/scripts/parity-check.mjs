import { chromium } from '@playwright/test'
import assert from 'node:assert/strict'
const browser = await chromium.launch()
const page = await browser.newPage({ locale: 'zh-CN', viewport: { width: 1440, height: 1000 } })
const calls = []
await page.route('**/*', route => {
  const url = new URL(route.request().url()), path = url.pathname
  if (path === '/sysinfo') return route.fulfill({ json: { board: { model: 'Parity Board' } } })
  if (path === '/version') return route.fulfill({ body: 'Test U-Boot' })
  if (path === '/theme/get') return route.fulfill({ json: { theme: 'light', color: '#2563eb', dark_variant: '' } })
  if (path === '/getmtdlayout') return route.fulfill({ body: 'default;default;custom;' })
  if (url.searchParams.has('_probe')) return route.fulfill({ body: 'enabled' })
  if (path === '/backup/info') return route.fulfill({ json: { mtd: { present: true, nand_raw_size: 2176, ram_available: 65536, nand_page_size: 256, nand_oob_size: 16, parts: [{ name: 'spi0', size: 2048, master: true, page_size: 256, oob_size: 16, erase_size: 512 }] } } })
  if (path === '/flash/read') return route.fulfill({ json: { ok: true, data: '00'.repeat(512) } })
  if (path === '/ubi/info') return route.fulfill({ json: { attached: true, mtd_name: 'ubi', leb_size: 126976 } })
  if (path === '/ubi/mtd_list') return route.fulfill({ json: { partitions: [{ name: 'ubi', size: 33554432 }] } })
  if (path === '/ubi/volumes') return route.fulfill({ json: { volumes: [{ name: 'rootfs', size: 4096, used_bytes: 512, type: 'static', skip_check: true, corrupted: false }] } })
  if (path === '/ubi/check') return route.fulfill({ json: { exists: true } })
  if (route.request().method() === 'POST' && /^\/(flash|ubi)\//.test(path)) { calls.push({ path, body: route.request().postData() }); return route.fulfill({ json: { ok: true } }) }
  return route.continue()
})
await page.goto('http://localhost:5173/#/flash')
await page.getByRole('button', { name: '读取', exact: true }).click()
await page.getByRole('group', { name: '字节选区' }).waitFor()
await page.getByRole('button', { name: '0x0: 00', exact: true }).click()
await page.getByRole('button', { name: '0x3: 00', exact: true }).click({ modifiers: ['Shift'] })
assert.equal(await page.locator('.hex-grid button[aria-pressed="true"]').count(), 4)
await page.getByRole('textbox', { name: '填充字节', exact: true }).fill('ff')
await page.getByRole('button', { name: '填充选区', exact: true }).click()
assert.match(await page.getByRole('textbox', { name: '十六进制编辑器' }).inputValue(), /^ff ff ff ff 00/)
await page.getByRole('button', { name: '写入修改', exact: true }).click()
await page.getByRole('button', { name: '确认', exact: true }).click()
await page.waitForTimeout(200)
assert.ok(calls.find(call => call.path === '/flash/write' && call.body.includes('ffffffff')))
await page.locator('input[type=file]').setInputFiles({ name: 'backup_Parity_Board_mtd_chip_spi0_oob_0x0-0x220_20260309.bin', mimeType: 'application/octet-stream', buffer: Buffer.alloc(544) })
await page.getByRole('button', { name: '恢复备份', exact: true }).click()
await page.getByRole('button', { name: '确认', exact: true }).click()
await page.waitForTimeout(300)
const restore = calls.find(call => call.path === '/flash/restore')
assert.ok(restore)
assert.match(restore.body, /name="raw"\r\n\r\n1/)
assert.match(restore.body, /0x220/)
await page.getByRole('menuitem', { name: 'UBI 卷管理', exact: true }).click()
await page.getByRole('button', { name: '检查', exact: true }).click()
await page.getByText('rootfs: 卷存在', { exact: true }).waitFor()
await page.getByRole('button', { name: '启用 CRC', exact: true }).click()
await page.getByRole('button', { name: '确认', exact: true }).click()
await page.waitForTimeout(200)
assert.match(calls.find(call => call.path === '/ubi/skipcheck').body, /name="mode"\r\n\r\n0/)
await page.getByRole('button', { name: '写入', exact: true }).click()
await page.getByRole('dialog').locator('input[type=file]').setInputFiles({ name: 'rootfs.bin', mimeType: 'application/octet-stream', buffer: Buffer.alloc(1024) })
await page.getByRole('dialog').getByRole('button', { name: '写入', exact: true }).click()
await page.getByRole('button', { name: '确认', exact: true }).click()
await page.waitForTimeout(300)
assert.ok(calls.find(call => call.path === '/ubi/write'))
await page.setViewportSize({ width: 375, height: 812 })
await page.waitForTimeout(500)
assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
console.log('Parity tests passed: byte range fill/write, OOB name detection and explicit raw restore, UBI check detail, correct CRC inverse, upload progress, mobile layout.')
await browser.close()
