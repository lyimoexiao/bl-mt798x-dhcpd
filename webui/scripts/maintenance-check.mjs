import { chromium } from '@playwright/test'
import assert from 'node:assert/strict'
const browser = await chromium.launch()
const page = await browser.newPage({ locale: 'zh-CN', viewport: { width: 1440, height: 1000 } })
await page.addInitScript(() => { window.showSaveFilePicker = undefined })
const errors = [], calls = []
page.on('pageerror', error => errors.push(error.message))
await page.route('**/*', async route => {
  const url = new URL(route.request().url())
  const path = url.pathname
  if (path === '/sysinfo') return route.fulfill({ json: { board: { model: 'Maintenance Test' }, ram: { size: 268435456 } } })
  if (path === '/version') return route.fulfill({ body: 'U-Boot Test' })
  if (url.searchParams.has('_probe')) return route.fulfill({ body: 'enabled' })
  if (path === '/theme/get') return route.fulfill({ json: { theme: 'light', color: '#2563eb', dark_variant: '' } })
  if (path === '/getmtdlayout') return route.fulfill({ body: 'default;default;custom;' })
  if (path === '/env/list') return route.fulfill({ body: 'ipaddr=192.168.1.1\nnetmask=255.255.255.0\nserverip=192.168.1.254\nbootdelay=3\n' })
  if (path === '/env/size') return route.fulfill({ body: '64 / 4096' })
  if (path === '/backup/info') return route.fulfill({ json: { mmc: { present: false, parts: [] }, mtd: { present: true, parts: [{ name: 'firmware', size: 33554432 }] } } })
  if (path === '/backup/main') { calls.push(path); return route.fulfill({ body: Buffer.from('backup'), contentType: 'application/octet-stream', headers: { 'Content-Length': '6' } }) }
  if (path === '/ubi/info') return route.fulfill({ json: { attached: true } })
  if (path === '/ubi/mtd_list') return route.fulfill({ json: { partitions: [{ name: 'ubi', size: 33554432 }] } })
  if (path === '/ubi/volumes') return route.fulfill({ json: { volumes: [{ name: 'rootfs', size: 4096, used_bytes: 512, type: 'dynamic', skip_check: false }] } })
  if (path === '/flash/read') return route.fulfill({ json: { ok: true, data: 'aa'.repeat(512) } })
  if (route.request().method() === 'POST' && /^\/(env|ubi|flash|theme)\//.test(path)) { calls.push(path); return route.fulfill({ json: { ok: true } }) }
  return route.continue()
})
await page.goto('http://localhost:5173/#/env')
await page.getByText('bootdelay', { exact: true }).waitFor()
assert.equal(await page.locator('iframe').count(), 0)
await page.getByRole('textbox').nth(1).fill('test_key')
await page.getByRole('textbox').nth(2).fill('test_value')
await page.getByRole('button', { name: '保存变量', exact: true }).click()
await page.getByRole('button', { name: '确认', exact: true }).click()
await page.waitForTimeout(250)
assert.ok(calls.includes('/env/set'))
await page.getByRole('menuitem', { name: '设备设置', exact: true }).click()
await page.getByRole('button', { name: '保存设置', exact: true }).waitFor()
await page.getByRole('menuitem', { name: '备份与恢复', exact: true }).click()
await page.getByRole('button', { name: '下载备份', exact: true }).waitFor()
const download = page.waitForEvent('download')
await page.getByRole('button', { name: '下载备份', exact: true }).click()
await download
assert.ok(calls.includes('/backup/main'))
await page.getByRole('menuitem', { name: 'Flash 工具', exact: true }).click()
await page.getByRole('button', { name: '读取', exact: true }).click()
await page.getByRole('textbox', { name: '十六进制编辑器' }).waitFor()
assert.match(await page.getByRole('textbox', { name: '十六进制编辑器' }).inputValue(), /aa aa/)
await page.getByRole('menuitem', { name: 'UBI 卷管理', exact: true }).click()
await page.getByText('rootfs', { exact: true }).waitFor()
await page.getByRole('button', { name: '检查', exact: true }).click()
await page.waitForTimeout(200)
assert.ok(calls.includes('/ubi/check'))
await page.getByRole('menuitem', { name: '重启与启动', exact: true }).click()
await page.getByRole('button', { name: '重启设备', exact: true }).waitFor()
assert.equal(await page.locator('iframe').count(), 0)
assert.deepEqual(errors, [])
console.log('Maintenance checks passed: native pages, env mutation confirmation, settings rendering, backup download, flash hex read, UBI check, reboot actions, no iframe/runtime errors.')
await browser.close()
