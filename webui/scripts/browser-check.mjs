// Console uses xterm and the original command/poll protocol.
const terminalPage = await context.newPage()
await terminalPage.route('**/version', route => route.fulfill({ body: 'U-Boot Test' }))
await terminalPage.route('**/sysinfo', route => route.fulfill({ json: { board: { model: 'Terminal Test' } } }))
await terminalPage.route('**/*.html?_probe=1', route => route.fulfill({ status: route.request().url().includes('console.html') ? 200 : 404, body: 'probe' }))
let commandSeen = ''
let outputSent = false
await terminalPage.route('**/console/poll', route => {
  const data = commandSeen && !outputSent ? '\\u001b[32mU-Boot test output\\u001b[0m\\r\\n' : ''
  if (data) outputSent = true
  return route.fulfill({ json: { data, busy: false } })
})
await terminalPage.route('**/console/exec', route => { commandSeen = route.request().postData() || ''; return route.fulfill({ json: { ret: 0 } }) })
await terminalPage.goto('http://localhost:5173/#/console')
await terminalPage.getByRole('button', { name: '连接终端', exact: true }).waitFor()
await terminalPage.waitForFunction(() => !document.querySelector('.console-panel .el-empty'))
await terminalPage.getByRole('button', { name: '连接终端', exact: true }).click()
await terminalPage.getByRole('textbox', { name: '命令', exact: true }).fill('version')
await terminalPage.getByRole('button', { name: '执行命令', exact: true }).click()
await terminalPage.getByText('返回码: 0', { exact: true }).waitFor()
assert.match(commandSeen, /version/)
await terminalPage.locator('.xterm').waitFor()
await terminalPage.waitForTimeout(800)
assert.equal(outputSent, true)
await terminalPage.screenshot({ path: 'screenshots/console-xterm.png', fullPage: true })
const headerTop = await terminalPage.locator('.topbar').evaluate(e => e.getBoundingClientRect().top)
await terminalPage.locator('#main-content').evaluate(e => { e.scrollTop = 300 })
assert.equal(await terminalPage.locator('.topbar').evaluate(e => e.getBoundingClientRect().top), headerTop)
console.log('Confirmed: xterm mounted, console protocol, output polling, fixed header.')
await browser.close()
